//! 다국어 지원 — 문자열 테이블과 현재 언어 상태.
//!
//! 모든 번역은 `translations!` 표 하나에 모아 두어 키를 추가할 때
//! 9개 언어를 한자리에서 채울 수 있게 했다. 배경 스레드(tools/engine)도
//! 문자열을 만들어야 하므로 현재 언어는 전역 원자 변수로 보관한다.

use std::sync::atomic::{AtomicU8, Ordering};

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Ja,
    Ko,
    Zh,
    Ar,
    De,
    Fr,
    Es,
    Pt,
}

pub const ALL_LANGS: [Lang; 9] = [
    Lang::En,
    Lang::Ja,
    Lang::Ko,
    Lang::Zh,
    Lang::Ar,
    Lang::De,
    Lang::Fr,
    Lang::Es,
    Lang::Pt,
];

impl Lang {
    /// 설정 창에 표시할 이름 (각 언어의 자기 이름)
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
            Lang::Zh => "简体中文",
            Lang::Ar => "العربية",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::Pt => "Português",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Ja => "ja",
            Lang::Ko => "ko",
            Lang::Zh => "zh",
            Lang::Ar => "ar",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::Pt => "pt",
        }
    }

    /// "ko_KR.UTF-8", "zh-Hans-CN", "pt_BR" 같은 로케일 태그에서 언어를 고른다.
    pub fn from_tag(tag: &str) -> Option<Lang> {
        let head = tag
            .split(['_', '-', '.', '@'])
            .next()
            .unwrap_or("")
            .to_ascii_lowercase();
        ALL_LANGS.into_iter().find(|l| l.code() == head)
    }

    fn from_u8(v: u8) -> Lang {
        ALL_LANGS.get(v as usize).copied().unwrap_or(Lang::En)
    }

    fn to_u8(self) -> u8 {
        ALL_LANGS.iter().position(|l| *l == self).unwrap_or(0) as u8
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(l: Lang) {
    CURRENT.store(l.to_u8(), Ordering::Relaxed);
}

pub fn lang() -> Lang {
    Lang::from_u8(CURRENT.load(Ordering::Relaxed))
}

/// 설정값(None = 시스템 언어)을 실제 언어로 확정하고 전역에 반영한다.
pub fn apply_pref(pref: Option<Lang>) -> Lang {
    let l = pref.unwrap_or_else(detect_system_lang);
    set_lang(l);
    l
}

/// OS 의 표시 언어를 추정한다. 알 수 없으면 영어.
///
/// 아는 언어로 이어지는 첫 후보를 쓴다. 그래서 `LANG=C.UTF-8` 처럼
/// 언어를 담고 있지 않은 로케일은 답으로 삼지 않고 다음 후보로 넘어간다.
pub fn detect_system_lang() -> Lang {
    locale_candidates()
        .iter()
        .find_map(|tag| Lang::from_tag(tag))
        .unwrap_or(Lang::En)
}

fn locale_candidates() -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for key in ["LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(v) = std::env::var(key) {
            if !v.is_empty() {
                out.push(v);
            }
        }
    }

    // macOS: .app 번들로 실행하면 LANG 이 비어 있으므로 사용자 기본 로케일을 직접 읽는다.
    #[cfg(target_os = "macos")]
    if let Ok(o) = crate::util::new_command("defaults")
        .args(["read", "-g", "AppleLocale"])
        .output()
    {
        let s = String::from_utf8_lossy(&o.stdout).trim().to_string();
        if !s.is_empty() {
            out.push(s);
        }
    }

    #[cfg(windows)]
    if let Some(s) = windows_ui_lang() {
        out.push(s);
    }

    out
}

/// Windows 표시 언어(LANGID)의 기본 언어 부분만 본다.
#[cfg(windows)]
fn windows_ui_lang() -> Option<String> {
    #[link(name = "kernel32")]
    extern "system" {
        fn GetUserDefaultUILanguage() -> u16;
    }
    let primary = unsafe { GetUserDefaultUILanguage() } & 0x3ff;
    let code = match primary {
        0x01 => "ar",
        0x04 => "zh",
        0x07 => "de",
        0x09 => "en",
        0x0a => "es",
        0x0c => "fr",
        0x11 => "ja",
        0x12 => "ko",
        0x16 => "pt",
        _ => return None,
    };
    Some(code.to_string())
}

/// 현재 언어의 문자열.
pub fn t(k: Key) -> &'static str {
    k.get(lang())
}

/// `{0}`, `{1}` … 자리표시자를 채운 문자열.
/// (언어마다 어순이 다르므로 번호를 붙여 순서를 바꿀 수 있게 했다)
pub fn tf(k: Key, args: &[&str]) -> String {
    let s = t(k);
    let mut out = String::with_capacity(s.len() + 16);
    let mut rest = s;
    while let Some(open) = rest.find('{') {
        out.push_str(&rest[..open]);
        let after = &rest[open + 1..];
        let Some(close) = after.find('}') else {
            out.push_str(&rest[open..]);
            return out;
        };
        match after[..close].parse::<usize>() {
            Ok(i) => out.push_str(args.get(i).copied().unwrap_or("")),
            // 번호가 아니면 원문 그대로 둔다.
            Err(_) => {
                out.push('{');
                out.push_str(&after[..close]);
                out.push('}');
            }
        }
        rest = &after[close + 1..];
    }
    out.push_str(rest);
    out
}

macro_rules! translations {
    ($( $key:ident => {
        en: $en:expr,
        ja: $ja:expr,
        ko: $ko:expr,
        zh: $zh:expr,
        ar: $ar:expr,
        de: $de:expr,
        fr: $fr:expr,
        es: $es:expr,
        pt: $pt:expr $(,)?
    } ),* $(,)?) => {
        #[allow(dead_code)]
        #[derive(Clone, Copy, PartialEq, Eq, Debug)]
        pub enum Key { $($key),* }

        impl Key {
            /// 표 전체 검사를 위한 목록 (테스트용)
            #[cfg(test)]
            pub const ALL: &'static [Key] = &[$(Key::$key),*];

            pub fn get(self, lang: Lang) -> &'static str {
                match self {
                    $(Key::$key => match lang {
                        Lang::En => $en,
                        Lang::Ja => $ja,
                        Lang::Ko => $ko,
                        Lang::Zh => $zh,
                        Lang::Ar => $ar,
                        Lang::De => $de,
                        Lang::Fr => $fr,
                        Lang::Es => $es,
                        Lang::Pt => $pt,
                    }),*
                }
            }
        }
    };
}

