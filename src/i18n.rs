#[cfg(test)]
mod tests {
    use super::*;

    /// `{0}` 같은 자리표시자를 모아 반환한다.
    fn placeholders(s: &str) -> Vec<usize> {
        let mut out = Vec::new();
        let mut rest = s;
        while let Some(open) = rest.find('{') {
            let after = &rest[open + 1..];
            let Some(close) = after.find('}') else { break };
            if let Ok(i) = after[..close].parse::<usize>() {
                out.push(i);
            }
            rest = &after[close + 1..];
        }
        out.sort_unstable();
        out.dedup();
        out
    }

    #[test]
    fn every_key_is_translated_in_every_language() {
        for k in Key::ALL {
            for l in ALL_LANGS {
                assert!(
                    !k.get(l).trim().is_empty(),
                    "{k:?} 의 {} 번역이 비어 있습니다",
                    l.code()
                );
            }
        }
    }

    /// 어순은 달라도 되지만, 쓰이는 자리표시자 번호는 언어마다 같아야 한다.
    /// (하나라도 빠지면 값이 조용히 사라진다)
    #[test]
    fn placeholders_match_across_languages() {
        for k in Key::ALL {
            let want = placeholders(k.get(Lang::En));
            for l in ALL_LANGS {
                assert_eq!(
                    placeholders(k.get(l)),
                    want,
                    "{k:?} 의 {} 자리표시자가 영어와 다릅니다",
                    l.code()
                );
            }
        }
    }

    #[test]
    fn locale_tags_map_to_languages() {
        assert_eq!(Lang::from_tag("ko_KR.UTF-8"), Some(Lang::Ko));
        assert_eq!(Lang::from_tag("zh-Hans-CN"), Some(Lang::Zh));
        assert_eq!(Lang::from_tag("pt_BR"), Some(Lang::Pt));
        assert_eq!(Lang::from_tag("ar"), Some(Lang::Ar));
        assert_eq!(Lang::from_tag("C"), None);
        assert_eq!(Lang::from_tag("C.UTF-8"), None);
        assert_eq!(Lang::from_tag("POSIX"), None);
        assert_eq!(Lang::from_tag(""), None);
    }

    /// 현재 언어는 전역 값이라, 이를 건드리는 검사는 한 테스트로 묶어
    /// 병렬 실행끼리 서로 간섭하지 않게 한다.
    #[test]
    fn current_language_drives_lookup() {
        for l in ALL_LANGS {
            set_lang(l);
            assert_eq!(lang(), l);
            assert_eq!(t(Key::BtnAdd), Key::BtnAdd.get(l));
        }

        set_lang(Lang::En);
        assert_eq!(tf(Key::ToastAdded, &["3"]), "3 added");
        assert_eq!(
            tf(Key::MsgApplied, &["yt-dlp", "2025.01.01"]),
            "yt-dlp 2025.01.01 applied"
        );
        // 인자가 모자라면 빈 문자열로 둘 뿐, 패닉하지 않는다.
        assert_eq!(tf(Key::ToastAdded, &[]), " added");

        set_lang(Lang::Ko);
        assert_eq!(tf(Key::ToastAdded, &["3"]), "3개 추가됨");
    }
}
